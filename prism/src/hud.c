// Both fields live in background row 0, which the grid (rows 3-14)
// never touches - no column-dodging needed. No text labels
// ("SCORE"/"MOVES") this pass, since there's no letter glyph set - a
// fixed left/right screen position convention instead (a real labeled
// HUD is Milestone 6 material).
#define SCORE_X 1
#define SCORE_DIGITS 4
#define MOVES_X 17
#define MOVES_DIGITS 2
#define HUD_Y 0

static void draw_number(uint8_t x, uint8_t y, uint16_t value, uint8_t digits) {
    uint8_t buf[SCORE_DIGITS]; // SCORE_DIGITS (4) is the largest field used
    for (int8_t i = (int8_t)digits - 1; i >= 0; i--) {
        buf[i] = (uint8_t)(HUD_DIGIT_TILE_BASE + (value % 10));
        value /= 10;
    }
    set_bkg_tiles(x, y, digits, 1, buf);
}

void hud_set_score(uint16_t score) {
    draw_number(SCORE_X, HUD_Y, score, SCORE_DIGITS);
}

void hud_set_moves(uint8_t moves) {
    draw_number(MOVES_X, HUD_Y, moves, MOVES_DIGITS);
}

void hud_init(void) {
    set_bkg_data(HUD_DIGIT_TILE_BASE, HUD_DIGIT_COUNT, digit_tiles);
}
